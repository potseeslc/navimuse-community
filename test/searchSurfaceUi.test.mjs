import test from 'node:test';
import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { createServer } from 'vite';

test('Search protects current results, reports failures, retries, and preserves selected-result actions', async () => {
  const window = new Window({url:'http://localhost/'});
  for (const key of ['window','document','Node','Element','HTMLElement','CustomEvent']) globalThis[key] = key === 'window' ? window : window[key];
  globalThis.requestAnimationFrame = window.requestAnimationFrame.bind(window);
  Object.defineProperty(globalThis,'navigator',{value:window.navigator,configurable:true});
  const requests = [];
  globalThis.fetch = (url,init) => new Promise(resolve => requests.push({url:String(url),signal:init?.signal,resolve}));
  const vite = await createServer({server:{middlewareMode:true,hmr:false},appType:'custom',optimizeDeps:{noDiscovery:true}});
  const React = await import('react');
  const {createRoot} = await import('react-dom/client');
  const {flushSync} = await import('react-dom');
  const {SearchSurface} = await vite.ssrLoadModule('/src/librarySearchSurfaces.jsx');
  const node = document.createElement('div'); document.body.append(node);
  const root = createRoot(node);
  const wait = async predicate => { for(let i=0;i<100;i++){if(predicate()) return; await new Promise(r=>setTimeout(r,10));} assert.fail('Expected search state'); };
  const payload = title => Response.json({artists:[],albums:[],songs:[{id:title,title,artist:'Artist'}]});
  let selected, album, changed, albumOpener;
  const props = {libraryKey:'first',onQueryChange:q=>{changed=q;},onPlaySong:(song,songs)=>{selected={song,songs};},onPlayAlbum:(a,opener)=>{album=a;albumOpener=opener;}};
  const render = query => flushSync(()=>root.render(React.createElement(SearchSurface,{...props,query})));
  try {
    render('older'); await wait(()=>requests.length===1);
    render('newer'); await wait(()=>requests.length===2);
    assert.equal(requests[0].signal.aborted,true);
    requests[1].resolve(payload('New song')); await wait(()=>node.textContent.includes('New song'));
    requests[0].resolve(Response.json({error:'old failure'},{status:503}));
    await new Promise(r=>setTimeout(r,30));
    assert.match(node.textContent,/New song/);
    assert.equal(node.querySelector('[role="alert"]'),null);
    node.querySelector('.actionable-result-row > button').click();
    assert.equal(selected.song.id,'New song');
    assert.deepEqual(selected.songs.map(s=>s.id),['New song']);
    render('scope'); await wait(()=>requests.length===3);
    props.libraryKey='second'; render('scope'); await wait(()=>requests.length===4);
    assert.equal(requests[2].signal.aborted,true);
    assert.match(requests[3].url,/musicFolderId=second/);
    assert.equal(node.querySelector('.search-box input').value,'scope','Changing libraries reruns the listener query in the new scope');
    assert.doesNotMatch(node.textContent,/New song/,'Previous results are removed while the new scope loads');
    requests[3].resolve(payload('Scoped song')); await wait(()=>node.textContent.includes('Scoped song'));
    requests[2].resolve(payload('Wrong scope')); await new Promise(r=>setTimeout(r,30));
    assert.doesNotMatch(node.textContent,/Wrong scope/);
    render('failure'); await wait(()=>requests.length===5);
    requests[4].resolve(Response.json({error:'offline'},{status:503})); await wait(()=>node.querySelector('[role="alert"]'));
    assert.doesNotMatch(node.textContent,/No matches/);
    assert.doesNotMatch(node.textContent,/Scoped song/,'A failed new query does not leave old results actionable');
    assert.equal(node.querySelector('.actionable-result-row'),null);
    const queryRetry=[...node.querySelectorAll('button')].find(b=>b.textContent==='Retry search');
    queryRetry.focus(); queryRetry.click(); await wait(()=>requests.length===6);
    assert.ok(document.activeElement===node.querySelector('.search-box input'),'Search Retry retains query focus while its button disappears');
    requests[5].resolve(Response.json({artists:[],albums:[{id:'album',name:'Recovered album'}],songs:[]})); await wait(()=>node.textContent.includes('Recovered album'));
    const resultAlbumButton=node.querySelector('[aria-labelledby="search-albums-title"] button');
    resultAlbumButton.click(); assert.equal(album.id,'album');
    assert.equal(albumOpener,resultAlbumButton,'pointer activation forwards the opener even when the browser does not focus buttons');
    render('pending'); await wait(()=>requests.length===7);
    render('x'); await wait(()=>!node.querySelector('[role="status"]'));
    requests[6].resolve(payload('Too late')); await new Promise(r=>setTimeout(r,30));
    assert.doesNotMatch(node.textContent,/Too late/);
    assert.match(node.textContent,/at least two characters/);
    [...node.querySelectorAll('button')].find(b=>b.textContent==='Beatles').click(); assert.equal(changed,'Beatles');
    render('artist'); await wait(()=>requests.length===8);
    requests[7].resolve(Response.json({artists:[{id:'artist-id',name:'Chosen Artist'}],albums:[],songs:[]}));
    await wait(()=>node.textContent.includes('Chosen Artist'));
    const artistButton=node.querySelector('[aria-labelledby="search-artists-title"] button');
    artistButton.click(); await wait(()=>requests.length===10);
    assert.match(requests[9].url,/artists\/artist-id\/profile/);
    requests[9].resolve(Response.json({artist:{id:'artist-id',name:'Chosen Artist'},popularAvailable:false,popular:[]}));
    assert.match(requests[8].url,/artistId=artist-id/);
    assert.match(requests[8].url,/musicFolderId=second/);
    requests[8].resolve(Response.json({error:'offline'},{status:503}));
    await wait(()=>node.querySelector('.search-artist-detail [role="alert"]'));
    const artistRetry=node.querySelector('.search-artist-detail [role="alert"] button');
    artistRetry.focus(); artistRetry.click();
    await wait(()=>requests.length===11);
    assert.ok(document.activeElement===node.querySelector('.search-artist-detail h1'),'Retry retains keyboard context when its button disappears');
    requests[10].resolve(Response.json({albums:[{id:'artist-album',name:'Artist Album'}],page:{nextOffset:null}}));
    await wait(()=>node.textContent.includes('Artist Album'));
    assert.equal(document.activeElement.textContent,'Chosen Artist');
    const artistAlbumButton=node.querySelector('.search-artist-detail .library-card');
    artistAlbumButton.click(); assert.equal(album.id,'artist-album');
    assert.equal(albumOpener,artistAlbumButton,'artist album drilldown forwards the actual opener');
    [...node.querySelectorAll('button')].find(b=>b.textContent.includes('Back to Search')).click();
    await wait(()=>document.activeElement===artistButton);
    assert.equal(node.querySelector('.search-box input').value,'artist');
    artistButton.click(); await wait(()=>node.querySelector('.search-artist-detail'));
    const shortcut = new window.KeyboardEvent('keydown',{key:'/',bubbles:true,cancelable:true});
    document.activeElement.dispatchEvent(shortcut);
    await wait(()=>document.activeElement===node.querySelector('.search-box input'));
    assert.equal(shortcut.defaultPrevented,true);
    assert.equal(node.querySelector('.search-artist-detail'),null);
    props.shortcutsEnabled=false; render('artist');
    const coveredShortcut = new window.KeyboardEvent('keydown',{key:'/',bubbles:true,cancelable:true});
    window.dispatchEvent(coveredShortcut);
    assert.equal(coveredShortcut.defaultPrevented,false,'covered Search must not intercept a shortcut');
    props.shortcutsEnabled=true; render('artist');
    const modified = new window.KeyboardEvent('keydown',{key:'/',ctrlKey:true,bubbles:true,cancelable:true});
    window.dispatchEvent(modified); assert.equal(modified.defaultPrevented,false);

    render('jazz'); await wait(()=>requests.some(r=>r.url.includes('q=jazz')));
    requests.find(r=>r.url.includes('q=jazz')).resolve(Response.json({artists:[],albums:[],songs:[],genres:[{value:'Jazz Fusion'}]}));
    await wait(()=>node.querySelector('[aria-labelledby="search-genres-title"] button'));
    assert.doesNotMatch(node.textContent,/No matches/);
    const genreButton=node.querySelector('[aria-labelledby="search-genres-title"] button');
    genreButton.click(); await wait(()=>requests.some(r=>r.url.includes('genre=Jazz')));
    const genreRequest=requests.find(r=>r.url.includes('genre=Jazz'));
    assert.match(genreRequest.url,/musicFolderId=second/);
    genreRequest.resolve(Response.json({albums:[{id:'jazz-album',name:'Jazz Album'}],page:{nextOffset:null}}));
    await wait(()=>node.textContent.includes('Jazz Album'));
    node.querySelector('.search-artist-detail .library-card').click();assert.equal(album.id,'jazz-album');
    [...node.querySelectorAll('button')].find(b=>b.textContent.includes('Back to Search')).click();
    await wait(()=>document.activeElement===genreButton);
    assert.equal(node.querySelector('.search-box input').value,'jazz');

  } finally {flushSync(()=>root.unmount()); await vite.close(); await window.happyDOM.close();}
});
